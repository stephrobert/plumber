// Command gen rebuilds internal/lotp/catalog.json from the Living Off The
// Pipeline (LOTP) project — an open-source inventory of developer tools with
// RCE-by-design behaviour (https://github.com/boostsecurityio/lotp, Apache-2.0).
//
// It reads the `_tool/*.md` entries, keeps the CLI tools whose abuse category
// is config-file / input-file / env-var (the categories Plumber's LOTP control
// acts on — workflow `injection` entries are already covered by ISSUE-207/215),
// and emits a sorted JSON catalog.
//
// Usage:
//
//	go run ./internal/lotp/gen -out internal/lotp/catalog.json
//	go run ./internal/lotp/gen -src /path/to/local/lotp/checkout   # offline
//
// With no -src the generator fetches boostsecurityio/lotp pinned at lotpRef.
package main

import (
	"encoding/json"
	"flag"
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"sort"
	"strings"

	yaml "gopkg.in/yaml.v3"
)

// lotpRepo and lotpRef pin the upstream source for reproducible builds.
// Bump lotpRef and re-run `go generate ./internal/lotp` to refresh the catalog.
const (
	lotpRepo = "https://github.com/boostsecurityio/lotp"
	lotpRef  = "bae6d61f4178d52145155c1642b4ea09d035c532"
)

// abuseCategories are the LOTP tags the Plumber control reasons about: a tool
// in one of these categories runs attacker-supplied code when it processes a
// repository file or a poisoned environment variable.
var abuseCategories = map[string]bool{
	"config-file": true,
	"input-file":  true,
	"env-var":     true,
}

// commandOverride maps a LOTP entry file name to the actual executable name
// when they differ — the LOTP `title` is a display name ("Maven", "GoReleaser")
// and the file name is the better identifier, but a few still need a fix.
var commandOverride = map[string]string{
	"maven": "mvn",
}

// Tool is one RCE-by-design CLI entry of the catalog.
type Tool struct {
	Name       string   `json:"name"`
	Categories []string `json:"categories"`
	Files      []string `json:"files,omitempty"`
	Reference  string   `json:"reference,omitempty"`
}

// Catalog is the embedded dataset consumed by package lotp.
type Catalog struct {
	Comment   string `json:"_comment"`
	Source    string `json:"source"`
	SourceRef string `json:"sourceRef"`
	License   string `json:"license"`
	Tools     []Tool `json:"tools"`
}

// frontmatter mirrors the YAML header of a `_tool/*.md` LOTP entry.
type frontmatter struct {
	Title      string        `yaml:"title"`
	Tags       []string      `yaml:"tags"`
	Files      []string      `yaml:"files"`
	References stringOrSlice `yaml:"references"`
}

// stringOrSlice decodes a YAML field that LOTP writes inconsistently as either
// a bare scalar or a sequence (the `references:` key).
type stringOrSlice []string

func (s *stringOrSlice) UnmarshalYAML(node *yaml.Node) error {
	if node.Kind == yaml.ScalarNode {
		*s = []string{node.Value}
		return nil
	}
	var list []string
	if err := node.Decode(&list); err != nil {
		return err
	}
	*s = list
	return nil
}

func main() {
	src := flag.String("src", "", "local LOTP checkout (skips the network fetch)")
	out := flag.String("out", "catalog.json", "output path for the generated catalog")
	flag.Parse()

	root := *src
	if root == "" {
		dir, cleanup, err := fetchUpstream()
		if err != nil {
			fail("fetch upstream LOTP: %v", err)
		}
		defer cleanup()
		root = dir
	}

	tools, err := collect(filepath.Join(root, "_tool"))
	if err != nil {
		fail("collect tools: %v", err)
	}
	if len(tools) == 0 {
		fail("no tools collected — wrong -src path?")
	}

	catalog := Catalog{
		Comment:   "Generated by internal/lotp/gen from the Living Off The Pipeline (LOTP) project. Do not edit by hand — run `go generate ./internal/lotp`.",
		Source:    lotpRepo,
		SourceRef: lotpRef,
		License:   "Apache-2.0",
		Tools:     tools,
	}
	data, err := json.MarshalIndent(catalog, "", "  ")
	if err != nil {
		fail("marshal catalog: %v", err)
	}
	if err := os.WriteFile(*out, append(data, '\n'), 0o644); err != nil {
		fail("write %s: %v", *out, err)
	}
	fmt.Printf("wrote %d tools to %s\n", len(tools), *out)
}

// fetchUpstream clones boostsecurityio/lotp pinned at lotpRef into a temp dir.
func fetchUpstream() (dir string, cleanup func(), err error) {
	tmp, err := os.MkdirTemp("", "lotp-*")
	if err != nil {
		return "", nil, err
	}
	// Best-effort cleanup of the temp checkout; a failure here is harmless.
	cleanup = func() { _ = os.RemoveAll(tmp) }
	steps := [][]string{
		{"git", "-C", tmp, "init", "-q"},
		{"git", "-C", tmp, "remote", "add", "origin", lotpRepo},
		{"git", "-C", tmp, "fetch", "-q", "--depth", "1", "origin", lotpRef},
		{"git", "-C", tmp, "checkout", "-q", "FETCH_HEAD"},
	}
	for _, step := range steps {
		cmd := exec.Command(step[0], step[1:]...)
		cmd.Stderr = os.Stderr
		if runErr := cmd.Run(); runErr != nil {
			cleanup()
			return "", nil, fmt.Errorf("%s: %w", strings.Join(step, " "), runErr)
		}
	}
	return tmp, cleanup, nil
}

// collect parses every `_tool/*.md` entry under dir and returns the CLI tools
// that fall into an abuse category, sorted by name.
func collect(dir string) ([]Tool, error) {
	entries, err := os.ReadDir(dir)
	if err != nil {
		return nil, err
	}
	var tools []Tool
	for _, entry := range entries {
		if entry.IsDir() || !strings.HasSuffix(entry.Name(), ".md") {
			continue
		}
		raw, readErr := os.ReadFile(filepath.Join(dir, entry.Name()))
		if readErr != nil {
			return nil, fmt.Errorf("read %s: %w", entry.Name(), readErr)
		}
		fm, ok := parseFrontmatter(raw)
		if !ok {
			continue
		}
		tool, keep := toTool(entry.Name(), fm)
		if keep {
			tools = append(tools, tool)
		}
	}
	sort.Slice(tools, func(i, j int) bool { return tools[i].Name < tools[j].Name })
	return tools, nil
}

// parseFrontmatter extracts and decodes the leading `--- ... ---` YAML block.
func parseFrontmatter(content []byte) (frontmatter, bool) {
	s := string(content)
	if !strings.HasPrefix(s, "---") {
		return frontmatter{}, false
	}
	idx := strings.Index(s[3:], "\n---")
	if idx < 0 {
		return frontmatter{}, false
	}
	var fm frontmatter
	if err := yaml.Unmarshal([]byte(s[3:3+idx]), &fm); err != nil {
		return frontmatter{}, false
	}
	return fm, true
}

// toTool keeps a frontmatter entry only when it is a CLI tool carrying at least
// one abuse category, and projects it onto the catalog shape. The tool name is
// derived from the entry file name (the executable), not the LOTP `title`.
func toTool(filename string, fm frontmatter) (Tool, bool) {
	hasCLI := false
	var categories []string
	for _, tag := range fm.Tags {
		switch {
		case tag == "cli":
			hasCLI = true
		case abuseCategories[tag]:
			categories = append(categories, tag)
		}
	}
	if !hasCLI || len(categories) == 0 {
		return Tool{}, false
	}
	name := strings.TrimSuffix(filename, ".md")
	if override, ok := commandOverride[name]; ok {
		name = override
	}
	sort.Strings(categories)
	tool := Tool{Name: name, Categories: categories, Files: fm.Files}
	if len(fm.References) > 0 {
		tool.Reference = fm.References[0]
	}
	return tool, true
}

func fail(format string, args ...any) {
	fmt.Fprintf(os.Stderr, "lotp/gen: "+format+"\n", args...)
	os.Exit(1)
}
